def _send(client: Any, method: str, url: str, payload: dict[str, Any]) -> Any:
    return getattr(client, method)(
        url, payload, format="json", HTTP_X_CSRFTOKEN=csrf_value(client)
    )


def _in_english(client: Any, entry_id: str, slug: str, title: str, tags: list[str]) -> None:
    created = client.post(
        f"/api/v1/sites/entries/{entry_id}/translations/",
        {"locale": "en", "slug": slug, "title": title},
        format="json",
        HTTP_X_CSRFTOKEN=csrf_value(client),
        HTTP_IDEMPOTENCY_KEY=f"sections-translate-{slug}",
    )
    assert created.status_code == 201, created.data
    english = str(created.data["id"])
    save_entry_draft(
        client,
        english,
        expected_version=0,
        text=f"{title}.",
        idempotency_key=f"sections-draft-{slug}",
    )
    assert set_tags(client, english, tags).status_code == 200
    out = publish(client, english, idempotency_key=f"sections-publish-{slug}")
    assert out.status_code == 201, out.data


def _site() -> Blog:
    """A Polish site live in English and German. Its blog: five Polish
    articles on „Porady” (one also on „Drewno”, one asking not to be
    indexed), two of them in English, one in German. „Realizacje” beside it:
    two projects on „Drewno” (one also on „Porady”), one of them in English.
    The blog was `/blog/` everywhere, then `journal` in English and `ratgeber`
    in German, then `poradnik` and `magazine`; the blog and „Porady” are named
    in English."""
    blog = Blog("golden-sections")
    client = blog.client
    organization_id = Site.all_objects.get(pk=blog.site_id).organization_id
    Organization.objects.filter(pk=organization_id).update(public_locales=["pl", "en", "de"])
    second = str(_tagged_entry(client, blog.collection_id, "dwa", ["Porady"]).data["id"])
    _tagged_entry(client, blog.collection_id, "trzy", ["Porady", "Drewno"])
    _tagged_entry(client, blog.collection_id, "cztery", ["Porady"])
    hidden = create_entry(
        client, blog.collection_id, slug="wpis-ukryty", idempotency_key="sections-hidden"
    )
    hidden_id = str(hidden.data["id"])
    save_entry_draft(
        client,
        hidden_id,
        expected_version=0,
        text="Treść ukryta.",
        idempotency_key="sections-hidden-draft",
    )
    assert set_tags(client, hidden_id, ["Porady"]).status_code == 200
    asked = _send(
        client, "patch", f"/api/v1/sites/entries/{hidden_id}/metadata/", {"noindex": True}
    )
    assert asked.status_code == 200, asked.data
    out = publish(client, hidden_id, idempotency_key="sections-hidden-publish")
    assert out.status_code == 201, out.data
    _translation(client, blog.polish, "en", "first-one", "First one")
    _translation(client, second, "en", "second-one", "Second one")
    _translation(client, blog.polish, "de", "der-erste", "Der Erste")

    made = client.post(
        f"/api/v1/sites/{blog.site_id}/collections/",
        {
            "key": "realizacje",
            "name": "Realizacje",
            "kind": "blog",
            "base_path": "realizacje",
            "locale_paths": {"en": "projects", "de": "referenzen"},
        },
        format="json",
        HTTP_X_CSRFTOKEN=csrf_value(client),
        HTTP_IDEMPOTENCY_KEY="sections-projects",
    )
    assert made.status_code == 201, made.data
    projects = str(made.data["id"])
    for marker, slug, tags in (
        ("gdynia", "dom-w-gdyni", ["Drewno", "Porady"]),
        ("sopot", "dom-w-sopocie", ["Drewno"]),
    ):
        entry = create_entry(client, projects, slug=slug, idempotency_key=f"sections-{marker}")
        entry_id = str(entry.data["id"])
        save_entry_draft(
            client,
            entry_id,
            expected_version=0,
            text=f"Treść {marker}.",
            idempotency_key=f"sections-{marker}-draft",
        )
        assert set_tags(client, entry_id, tags).status_code == 200
        out = publish(client, entry_id, idempotency_key=f"sections-{marker}-publish")
        assert out.status_code == 201, out.data
        if marker == "gdynia":
            _in_english(client, entry_id, "house-in-gdynia", "House in Gdynia", ["Drewno"])
    linked = _send(
        client,
        "put",
        f"/api/v1/sites/collections/{projects}/navigation/",
        {"show_in_navigation": True},
    )
    assert linked.status_code == 200, linked.data

    for base_path, names in (
        ("blog", {"en": "journal", "de": "ratgeber"}),
        ("poradnik", {"en": "magazine", "de": "ratgeber"}),
    ):
        renamed = _send(
            client,
            "put",
            f"/api/v1/sites/collections/{blog.collection_id}/paths/",
            {"base_path": base_path, "locale_paths": names, "reason": "Nowa nazwa działu"},
        )
        assert renamed.status_code == 200, renamed.data
    # The site's tags are older than addresses per language: closed at their
    # keys, as the migration leaves every tag that was there before it.
    ContentTag.all_objects.filter(site_id=blog.site_id).update(slug_locked_at=LEGACY_TERM_LOCK)
    blog.english_names("Magazine", "Tips")
    return blog


def _read(blog: Blog) -> str:
    host = blog.host
    organization_id = Site.all_objects.get(pk=blog.site_id).organization_id
    with override_settings(SITES_ENTRY_INDEX_PAGE_SIZE=2):
        answers = {
            "pages": {path: _page(host, path) for path in _PAGES},
            "files": {
                f"{name}{'?locale=' + locale if locale else ''}": _file(host, name, locale)
                for name, locale in _FEEDS
            },
        }
        Organization.objects.filter(pk=organization_id).update(public_locales=["pl", "en"])
        answers["without_german"] = {
            "pages": {path: _page(host, path) for path in _WITHOUT_GERMAN},
            "files": {"sitemap.xml": _file(host, "sitemap.xml", None)},
        }
    return _normalized(
        json.dumps(answers, ensure_ascii=False, indent=1, sort_keys=True, default=str), host
    )


def _compare(read: str) -> None:
    if os.environ.get("SITES_GOLDEN_WRITE") == "1":
        GOLDEN.parent.mkdir(exist_ok=True)
        GOLDEN.write_text(read, encoding="utf-8")
    expected = GOLDEN.read_text(encoding="utf-8")
    if read != expected:
        got, want = read.splitlines(), expected.splitlines()
        pairs = enumerate(zip(got, want, strict=False))
        line = next(
            (index for index, pair in pairs if pair[0] != pair[1]), min(len(got), len(want))
        )
        pytest.fail(
            "The site answers differently from golden/sites_sections.json, first at line "
            f"{line + 1}:\n"
            f"  was: {want[line] if line < len(want) else '<end>'}\n"
            f"  is:  {got[line] if line < len(got) else '<end>'}"
        )


@pytest.mark.parametrize(
    "older", [False, True], ids=["publications-of-today", "publications-without-terms"]
)
def test_two_sections_answer_what_they_answered_before_categories(
    settings: Any, monkeypatch: pytest.MonkeyPatch, older: bool
) -> None:
    # German is not every product's language, nor a second section every
    # platform's offer; this site's company has both.
    settings.SITES_SUPPORTED_LOCALES = ("pl", "en", "de")
    settings.CONTENT_TYPES_OFFERED = True
    # The same file for publications as they are written now and as every
    # publication older than categories is stored: with no `terms`.
    if older:
        publications_as_before_terms(monkeypatch)
    site = _site()
    if older:
        assert_no_publication_names_terms(site.site_id)
    _compare(_read(site))
