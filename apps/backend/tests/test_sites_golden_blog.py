def _translation(client: Any, entry_id: str, locale: str, slug: str, title: str) -> None:
    created = client.post(
        f"/api/v1/sites/entries/{entry_id}/translations/",
        {"locale": locale, "slug": slug, "title": title},
        format="json",
        HTTP_X_CSRFTOKEN=csrf_value(client),
        HTTP_IDEMPOTENCY_KEY=f"golden-translate-{slug}",
    )
    assert created.status_code == 201, created.data
    translated = str(created.data["id"])
    save_entry_draft(
        client,
        translated,
        expected_version=0,
        text=f"{title}.",
        idempotency_key=f"golden-draft-{slug}",
    )
    assert set_tags(client, translated, ["Porady"]).status_code == 200
    published = publish(client, translated, idempotency_key=f"golden-publish-{slug}")
    assert published.status_code == 201, published.data


def _blog() -> Blog:
    """A Polish site live in English with a blog in its menu: four Polish
    articles on „Porady” (one also on „Drewno”), three of them in English,
    one in German; the blog and the subject named in English."""
    blog = Blog("golden-blog")
    organization_id = Site.all_objects.get(pk=blog.site_id).organization_id
    Organization.objects.filter(pk=organization_id).update(public_locales=["pl", "en", "de"])
    second = str(_tagged_entry(blog.client, blog.collection_id, "dwa", ["Porady"]).data["id"])
    third = str(
        _tagged_entry(blog.client, blog.collection_id, "trzy", ["Porady", "Drewno"]).data["id"]
    )
    _tagged_entry(blog.client, blog.collection_id, "cztery", ["Porady"])
    _translation(blog.client, blog.polish, "en", "first-one", "First one")
    _translation(blog.client, second, "en", "second-one", "Second one")
    _translation(blog.client, third, "en", "third-one", "Third one")
    _translation(blog.client, blog.polish, "de", "der-erste", "Der Erste")
    # The site's tags are older than addresses per language: closed at their
    # keys, as the migration leaves every tag that was there before it.
    ContentTag.all_objects.filter(site_id=blog.site_id).update(slug_locked_at=LEGACY_TERM_LOCK)
    blog.english_names("Journal", "Tips")
    return blog


def _page(host: str, path: str) -> dict[str, Any]:
    response = _get(host, path)
    answer: dict[str, Any] = {"status": response.status_code}
    if response.get("Location"):
        answer["location"] = response["Location"]
    if response.status_code == 200:
        answer["body"] = {
            key: value for key, value in response.data.items() if key not in _LEFT_OUT
        }
    return answer


def _file(host: str, name: str, locale: str | None) -> dict[str, Any]:
    if name == "llms.txt":
        with override_settings(PUBLIC_SITE_SCHEME="https"):
            response = APIClient().get(
                "/api/v1/public/site/llms.txt",
                {"locale": locale} if locale else {},
                HTTP_HOST=host,
                HTTP_ACCEPT="text/plain",
            )
    else:
        response = _feed(host, name, locale)
    return {
        "status": response.status_code,
        "type": response["Content-Type"],
        # One element a line, so a difference names the element.
        "body": response.content.decode().replace("><", ">\n<").splitlines(),
    }


def _read(blog: Blog) -> str:
    host = blog.host
    with override_settings(SITES_ENTRY_INDEX_PAGE_SIZE=2):
        answers = {
            "pages": {path: _page(host, path) for path in _PAGES},
            "files": {
                f"{name}{'?locale=' + locale if locale else ''}": _file(host, name, locale)
                for name, locale in _FEEDS
            },
        }
    return _normalized(
        json.dumps(answers, ensure_ascii=False, indent=1, sort_keys=True, default=str), host
    )


def _normalized(text: str, host: str) -> str:
    text = text.replace(host, "site.example")
    seen: dict[str, str] = {}

    def numbered(match: re.Match[str]) -> str:
        return seen.setdefault(match.group(0), f"<id-{len(seen) + 1}>")

    text = _UUID.sub(numbered, text)
    text = _DIGEST.sub("<digest>", text)
    for moment in _MOMENTS:
        text = moment.sub("<moment>", text)
    return text + "\n"


def _compare(read: str) -> None:
    if os.environ.get("SITES_GOLDEN_WRITE") == "1":
        GOLDEN.parent.mkdir(exist_ok=True)
        GOLDEN.write_text(read, encoding="utf-8")
    expected = GOLDEN.read_text(encoding="utf-8")
    if read != expected:
        got, want = read.splitlines(), expected.splitlines()
        pairs = enumerate(zip(got, want, strict=False))
        line = next(
            (index for index, pair in pairs if pair[0] != pair[1]), min(len(got), len(want))
        )
        pytest.fail(
            f"The blog answers differently from golden/sites_blog.json, first at line {line + 1}:\n"
            f"  was: {want[line] if line < len(want) else '<end>'}\n"
            f"  is:  {got[line] if line < len(got) else '<end>'}"
        )


@pytest.mark.parametrize("offered", [False, True], ids=["types-not-offered", "types-offered"])
def test_a_blog_answers_what_it_answered_before_content_types(
    settings: Any, offered: bool
) -> None:
    # German is not every product's language; this site's company speaks it.
    settings.SITES_SUPPORTED_LOCALES = ("pl", "en", "de")
    # One file for both: a platform that offers further content types changes
    # nothing for a company that makes none.
    settings.CONTENT_TYPES_OFFERED = offered
    _compare(_read(_blog()))
